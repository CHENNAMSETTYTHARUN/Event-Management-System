import io
import base64
import qrcode

def generate_qr_code(data: str) -> str:
    """
    Generates a base64 encoded PNG QR code for the given data.
    Returns a data URL scheme string that can be directly rendered in HTML/img tags.
    """
    qr = qrcode.QRCode(
        version=1,
        error_correction=qrcode.constants.ERROR_CORRECT_L,
        box_size=10,
        border=4,
    )
    qr.add_data(data)
    qr.make(fit=True)

    img = qr.make_image(fill_color="black", back_color="white")
    buffered = io.BytesIO()
    img.save(buffered, format="PNG")
    img_str = base64.b64encode(buffered.getvalue()).decode("utf-8")
    return f"data:image/png;base64,{img_str}"
